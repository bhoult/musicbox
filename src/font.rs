const SYMBOLS: &[u8] = b" -.:/!+()[],%#<>";

fn glyph(c: u8) -> Option<usize> {
    let c = c.to_ascii_uppercase();
    Some(match c {
        b'0'..=b'9' => (c - b'0') as usize,
        b'A'..=b'Z' => (c - b'A') as usize + 10,
        _ => SYMBOLS.iter().position(|&s| s == c)? + 36,
    })
}

/// A glyph's advance, in unscaled pixels.
pub const ADVANCE: i32 = 6;

/// How wide `s` draws at `scale` (the last glyph's gap left out).
pub fn width(s: &str, scale: i32) -> i32 {
    (s.len() as i32 * ADVANCE - 1).max(0) * scale
}

/// Draws `s` with its top left at (`x`, `y`) into `px` (`w` x `h`, 0xAARRGGBB),
/// clipped to the picture.
pub fn draw(px: &mut [u32], w: i32, h: i32, x: i32, y: i32, s: &str, rgb: u32, scale: i32) {
    for (i, c) in s.bytes().enumerate() {
        let Some(g) = glyph(c) else { continue };
        let gx = x + i as i32 * ADVANCE * scale;
        for (row, bits) in FONT[g].iter().enumerate() {
            for col in 0..5 {
                if bits & (0x10 >> col) == 0 {
                    continue;
                }
                for dy in 0..scale {
                    for dx in 0..scale {
                        let (px_, py) = (gx + col * scale + dx, y + row as i32 * scale + dy);
                        if px_ >= 0 && py >= 0 && px_ < w && py < h {
                            px[(py * w + px_) as usize] = 0xFF00_0000 | rgb;
                        }
                    }
                }
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_symbol_has_a_glyph() {
        assert_eq!(FONT.len(), 36 + SYMBOLS.len());
        for c in b"MUSICBOX 0123456789 c# lo-fi polka+techno [1/2] 50% <>".iter() {
            assert!(glyph(*c).is_some(), "{}", *c as char);
        }
        // drawn where asked, clipped at the edges
        let mut px = vec![0u32; 20 * 10];
        draw(&mut px, 20, 10, 15, 1, "#", 0xFFFFFF, 1);
        assert!(px.iter().any(|&p| p != 0));
        assert_eq!(width("AB", 2), 22);
    }
}
